    fun stationName(name: String): String {
        return IndicTransliteration.stationToLanguage(name, currentLanguage)
    }

    fun trainName(name: String): String {
        return IndicTransliteration.trainToLanguage(name, currentLanguage)
    }

    fun landmarkName(name: String): String {
        return IndicTransliteration.landmarkToLanguage(name, currentLanguage)
    }

    fun landmarkCategory(category: String): String {
        return when (category.lowercase()) {
            "heritage" -> t("cat_heritage")
            "monument" -> t("cat_monument")
            "river" -> t("cat_river")
            "bridge" -> t("cat_bridge")
            "mountain" -> t("cat_mountain")
            else -> category.replaceFirstChar { it.uppercase() }
        }
    }

    fun formatDelay(delayMinutes: Int): String {
        if (delayMinutes == 0) return t("on_time_label", "On Time")
        val absMinutes = kotlin.math.abs(delayMinutes)
        val durationStr = if (absMinutes >= 60) {
            val hrs = absMinutes / 60
            val rem = absMinutes % 60
            if (rem == 0) {
                if (currentLanguage == "en") "$hrs hr" else "$hrs घंटे"
            } else {
                if (currentLanguage == "en") "$hrs hr $rem min" else "$hrs घंटे $rem मिनट"
            }
        } else {
            if (currentLanguage == "en") "$absMinutes mins" else "$absMinutes मिनट"
        }
        return if (delayMinutes > 0) {
            if (currentLanguage == "en") "${t("delayed_by")} $durationStr"
            else "$durationStr ${t("delayed_by")}"
        } else {
            "$durationStr ${t("mins_early")}"
        }
    }

    fun formatHalt(minutes: Int): String {
        return "${t("halt")} $minutes${t("halt_mins")}"
    }

    fun formatPlatform(platform: String): String {
        val clean = platform.replace(Regex("^(PF|Platform|प्लेटफ़ॉर्म)\\s*", RegexOption.IGNORE_CASE), "").trim()
        return "${t("platform")} $clean"
    }

    fun formatPassThrough(count: Int): String {
        return "$count ${t("pass_through_stations")}"
    }

    fun formatCrossingStatus(name: String, isCrossing: Boolean): String {
        val localizedName = stationName(name)
        return if (isCrossing) {
            if (currentLanguage == "en") "${t("crossing")} $localizedName"
            else "$localizedName ${t("crossing")}"
        } else {
            if (currentLanguage == "en") "${t("at")} $localizedName"
            else "$localizedName ${t("at")}"
        }
    }

    fun formatKmRemaining(km: Int, destinationName: String): String {
        val localizedName = stationName(destinationName)
        return if (currentLanguage == "en") {
            "$km ${t("km_to")} $localizedName"
        } else {
            "$localizedName $km ${t("km_to")}"
        }
    }

