        private set

    fun setLanguage(code: String) {
        currentLanguage = code
        try {
            PlatformStorage.saveString(KEY_LANG, code)
        } catch (_: Throwable) {}
    }

    private fun loadSavedLanguage(): String {
        return try {
            PlatformStorage.getString(KEY_LANG)?.takeIf { code ->
                languages.any { it.code == code }
            } ?: "en"
        } catch (_: Throwable) {
            "en"
        }
    }

